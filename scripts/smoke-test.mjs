import { readFileSync, existsSync } from "node:fs";
import assert from "node:assert/strict";

const html=readFileSync("index.html","utf8");
const js=readFileSync("assets/js/app.js","utf8");
const css=readFileSync("assets/css/style.css","utf8");
const renderer=readFileSync("assets/js/globe3d.js","utf8");
const worker=readFileSync("assets/js/planet-worker.js","utf8");
const exportWorker=readFileSync("assets/js/export-worker.js","utf8");
const generator=readFileSync("assets/js/generator.js","utf8");
const historyModule=readFileSync("assets/js/history.js","utf8");
const shareModule=readFileSync("assets/js/share.js","utf8");

const ids=[...html.matchAll(/\bid=["']([^"']+)["']/g)].map(m=>m[1]);
const idSet=new Set(ids);
assert.equal(ids.length,idSet.size,"HTML must not contain duplicate ids");
const refs=[...js.matchAll(/\$\(["']([^"']+)["']\)/g)].map(m=>m[1]);
const missing=[...new Set(refs)].filter(id=>!idSet.has(id));
assert.deepEqual(missing,[],"Missing UI IDs: "+missing.join(", "));

for(const path of ["assets/css/style.css","assets/js/app.js","assets/js/globe3d.js","assets/js/generator.js","assets/js/planet-worker.js","assets/js/export-worker.js","assets/js/history.js","assets/js/share.js","assets/favicon.svg",".nojekyll"])assert.ok(existsSync(path),"Missing static asset "+path);
for(const symbol of ["generateRivers","generateCivilization","applyCustomCities","refreshCivilization","drawCivilizationGlobe","drawCivilizationMap","exportPNG","exportGeographyCSV","projectJSON","restoreProject","editOrAddCity","finishPlanetFields","createTerrainWorker"])assert.ok(js.includes("function "+symbol+"("),"Missing function "+symbol);
for(const id of ["showRivers","showCities","showRoutes","showBorders","regenerateCivBtn","cityCountStat","countryCountStat","riverCountStat","globe3dCanvas","undoBtn","redoBtn","shareBtn","tectonics","erosion","season"])assert.ok(idSet.has(id),"Missing interface control "+id);
for(const feature of ["uSurface","uMode","cloudNoise","uRotation","webglcontextlost"])assert.ok(renderer.includes(feature),"Missing WebGL feature "+feature);
assert.ok(worker.includes("importScripts")&&worker.includes("postMessage"),"Worker message transport incomplete");
assert.ok(exportWorker.includes("renderTexture")&&exportWorker.includes("postMessage"),"High-resolution export worker incomplete");
assert.ok(generator.includes("function renderTexture")&&generator.includes("pixels=new Uint8ClampedArray"),"Native resolution texture renderer missing");
assert.ok(generator.includes("function generateFields")&&generator.includes("boundary*stress*tectonics"),"Terrain generator missing plate model");
assert.ok(historyModule.includes("undoStack")&&historyModule.includes("redoStack"),"Undo/redo module incomplete");
assert.ok(shareModule.includes("createURL")&&shareModule.includes("readFromLocation"),"Share-link module incomplete");
assert.ok(html.includes('value="hydrology"')&&html.includes('value="political"'),"Map layers missing");
assert.ok(html.includes("assets/js/globe3d.js")&&html.includes("assets/js/history.js")&&html.includes("assets/js/share.js")&&html.includes("assets/js/generator.js"),"Scripts aren't loaded");
assert.ok(css.includes("#globe3dCanvas")&&css.includes(".history-button"),"Editor styles missing");
assert.ok(generator.includes("seasonal=-Math.cos(seasonPhase)")&&js.includes("Math.sin")&&js.includes("generateFields")&&js.includes("filledHeight"),"Terrain/hydrology model missing");
assert.ok(js.includes("JSON.stringify(job.settings) !== JSON.stringify(terrainSettings())"),"Stale worker jobs are not discarded");
assert.ok(js.includes("scale=[1,4,8].includes(Number(scale))"),"High resolution exports missing");

// Execute the pure terrain generator at a small resolution and check reproducibility.
await import("../assets/js/generator.js");
const config={width:96,height:48,seed:12345,temperature:4,humidity:58,relief:5,tectonics:65,erosion:20,season:50,seaLevel:50,landmass:0};
const a=globalThis.PlanetForgeGenerator.generateFields(config);
const b=globalThis.PlanetForgeGenerator.generateFields(config);
assert.equal(a.heightField.length,96*48);
assert.equal(a.temperature.length,96*48);
assert.ok(a.counts.reduce((sum,n)=>sum+n,0)===96*48,"Biome counts should cover every map cell");
assert.deepEqual(Array.from(a.heightField),Array.from(b.heightField),"Same seed/settings should generate identical terrain");
assert.deepEqual(Array.from(a.biome),Array.from(b.biome),"Same seed/settings should generate identical biomes");
assert.equal(typeof globalThis.PlanetForgeGenerator.renderTexture,"function","Generator API must expose the texture renderer used by the export Worker");
const texture=globalThis.PlanetForgeGenerator.renderTexture(config,"biome",{baseWidth:96,baseHeight:48});
assert.equal(texture.width,96);
assert.equal(texture.height,48);
assert.equal(texture.pixels.length,96*48*4,"Rendered texture should contain RGBA pixels");
assert.ok(texture.pixels.every((value,index)=>index%4!==3||value===255),"Every exported texel should be fully opaque");
assert.deepEqual(Array.from(texture.pixels),Array.from(globalThis.PlanetForgeGenerator.renderTexture(config,"biome",{baseWidth:96,baseHeight:48}).pixels),"Texture generation should be deterministic");
const temperatureTexture=globalThis.PlanetForgeGenerator.renderTexture(config,"temperature",{baseWidth:96,baseHeight:48});
assert.notDeepEqual(Array.from(texture.pixels),Array.from(temperatureTexture.pixels),"Different map layers must render different data");
const detailConfig={...config,width:192,height:96};
const detailTexture=globalThis.PlanetForgeGenerator.renderTexture(detailConfig,"elevation",{baseWidth:96,baseHeight:48});
assert.equal(detailTexture.width,192,"Native resolution export must use the requested width");
assert.equal(detailTexture.height,96,"Native resolution export must use the requested height");
assert.equal(detailTexture.pixels.length,192*96*4,"Native resolution export must allocate every RGBA pixel");
const winter=globalThis.PlanetForgeGenerator.generateFields({...config,season:0});
const summer=globalThis.PlanetForgeGenerator.generateFields({...config,season:50});
assert.notDeepEqual(Array.from(winter.temperature),Array.from(summer.temperature),"Season settings should affect temperature fields");
const quietPlates=globalThis.PlanetForgeGenerator.generateFields({...config,tectonics:0});
assert.notDeepEqual(Array.from(quietPlates.heightField),Array.from(a.heightField),"Tectonic activity should affect terrain elevation");
console.log("PlanetForge smoke tests passed: script wiring, WebGL, worker transport, deterministic terrain, climate, tectonics, texture layers, native-size export, gallery, editing, sharing and exports.");
